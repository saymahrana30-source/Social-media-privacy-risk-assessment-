"""Run the test-suite and build docs/TEST_RESULTS.md (Test ID, Scenario, Input, Expected, Actual, Pass/Fail).

Usage:  python tests/generate_test_report.py
"""
import subprocess
import sys
import xml.etree.ElementTree as ET
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
XML = ROOT / "reports" / "junit.xml"
OUT = ROOT / "docs" / "TEST_RESULTS.md"


def main():
    proc = subprocess.run([sys.executable, "-m", "pytest", "-q", f"--junitxml={XML}"], cwd=ROOT)
    rows, other_pass, other_fail = [], 0, 0
    for tc in ET.parse(XML).getroot().iter("testcase"):
        props = {p.get("name"): p.get("value") for p in tc.iter("property")}
        failed = tc.find("failure") is not None or tc.find("error") is not None
        if "test_id" in props:
            rows.append((props["test_id"], props["scenario"], props["input"], props["expected"],
                         props["actual"], "FAIL" if failed else "PASS"))
        elif failed:
            other_fail += 1
        else:
            other_pass += 1
    rows.sort(key=lambda r: (r[0][0], int(r[0][1:])))

    def esc(s):
        return s.replace("|", "\\|").replace("\n", " ")

    lines = [f"# Test results ({date.today().isoformat()})", "",
             "Generated by `python tests/generate_test_report.py` from a real pytest run.", "",
             "| Test ID | Scenario | Input | Expected result | Actual result | Pass/Fail |",
             "|---|---|---|---|---|---|"]
    lines += ["| " + " | ".join(esc(c) for c in r) + " |" for r in rows]
    lines += ["", f"Documented cases: {len(rows)} ({sum(r[5] == 'PASS' for r in rows)} passed). "
              f"Additional supporting tests: {other_pass + other_fail} ({other_pass} passed, {other_fail} failed).", "",
              "T-IDs cover functional/scoring tests; S-IDs cover security & privacy tests."]
    OUT.write_text("\n".join(lines) + "\n")
    print(f"Wrote {OUT}")
    return proc.returncode


if __name__ == "__main__":
    sys.exit(main())
